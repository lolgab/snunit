#!/usr/bin/env bash
# Builds one component of the observability stack so that it runs inside FreeUnit, and packages it with its licenses
# and the corresponding source of our modifications.
#
#   stack/build.sh <prometheus|jaeger|victorialogs|perses> [output dir]
#
# Environment:
#   FREEUNIT_SRC  FreeUnit source tree at the commit pinned in .github/freeunit-ref, configured (`./configure`) so that
#                 build/include exists. Provides the Go module (go/) and the C headers it needs.
#   LIBUNIT_DIR   directory containing the libunit.a built from that commit (the snunit `freeunit-<ref8>-<os>-<arch>`
#                 release archive)
#
# Produces <output dir>/snunit-stack-<role>-<os>-<arch>.tar.gz, with a single top-level directory `<role>`, where the role is
# metrics (Prometheus), traces (Jaeger), logs (VictoriaLogs) or dashboards (Perses).
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
component="${1:?usage: build.sh <prometheus|jaeger|victorialogs|perses> [output dir]}"
out="${2:-$PWD/dist}"
: "${FREEUNIT_SRC:?FREEUNIT_SRC is not set}"
: "${LIBUNIT_DIR:?LIBUNIT_DIR is not set}"
FREEUNIT_SRC="$(cd "$FREEUNIT_SRC" && pwd)"
LIBUNIT_DIR="$(cd "$LIBUNIT_DIR" && pwd)"
mkdir -p "$out"
out="$(cd "$out" && pwd)"
# `./configure` generates nxt_auto_config.h, the version header is generated by `make`: write it from the version file.
if [ ! -f "$FREEUNIT_SRC/build/include/nxt_version.h" ]; then
  (
    # shellcheck disable=SC1091
    . "$FREEUNIT_SRC/version"
    printf '#define NXT_VERSION "%s"\n#define NXT_VERNUM  %s\n' "$NXT_VERSION" "$NXT_VERNUM" \
      > "$FREEUNIT_SRC/build/include/nxt_version.h"
  )
fi
# shellcheck disable=SC1091
source "$here/versions.env"
freeunit_ref="$(tr -d '[:space:]' < "$here/../.github/freeunit-ref")"

case "$(uname -s)" in
  Linux) os=linux ;;
  Darwin) os=macos ;;
  *) echo "Unsupported OS: $(uname -s)" >&2; exit 1 ;;
esac
case "$(uname -m)" in
  x86_64 | amd64) arch=x86_64 ;;
  arm64 | aarch64) arch=aarch64 ;;
  *) echo "Unsupported architecture: $(uname -m)" >&2; exit 1 ;;
esac

# All the programs are Apache-2.0 and written in Go.
case "$component" in
  prometheus)   repo=prometheus/prometheus;          version="$PROMETHEUS_VERSION";   package=./cmd/prometheus;       role=metrics ;;
  jaeger)       repo=jaegertracing/jaeger;           version="$JAEGER_VERSION";       package=./cmd/jaeger;           role=traces ;;
  victorialogs) repo=VictoriaMetrics/VictoriaLogs;   version="$VICTORIALOGS_VERSION"; package=./app/victoria-logs;    role=logs ;;
  perses)       repo=perses/perses;                  version="$PERSES_VERSION";       package=./cmd/perses;           role=dashboards ;;
  *) echo "Unknown component: $component" >&2; exit 1 ;;
esac
license=Apache-2.0
case "$component" in
  victorialogs) trademark="VictoriaMetrics" ;;
  *) trademark="The Linux Foundation" ;;
esac
# The archives, the directories and the executables are named after what the program does, not after the project:
# trademarks (of the Linux Foundation, the CNCF, VictoriaMetrics...) shouldn't be part of the name of our product.
binary="snunit-$role"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
src="$work/src"
pkg="$work/pkg/$role"

echo "== Cloning $repo $version"
# Network failures happen: try a few times.
retry() {
  for attempt in 1 2 3; do
    "$@" && return 0
    echo "failed ($*), trying again" >&2
    sleep 10
  done
  return 1
}
rm -rf "$src"
retry git clone --quiet --depth 1 --branch "$version" "https://github.com/$repo" "$src"
if [ "$component" = jaeger ]; then
  # idl (protobuf definitions) is needed to compile, jaeger-ui for the web UI.
  retry git -C "$src" submodule update --quiet --init --depth 1 idl jaeger-ui
fi
commit="$(git -C "$src" rev-parse HEAD)"

echo "== Adding the FreeUnit Go module"
mkdir -p "$src/third_party/unit-go"
cp "$FREEUNIT_SRC"/go/*.go "$FREEUNIT_SRC"/go/*.c "$FREEUNIT_SRC"/go/*.h "$FREEUNIT_SRC"/go/go.mod "$src/third_party/unit-go/"
cp "$FREEUNIT_SRC/LICENSE" "$FREEUNIT_SRC/NOTICE" "$src/third_party/unit-go/"
if [ "$component" = jaeger ]; then
  # Shares the one handler FreeUnit gives to a program between the query server and the OTLP/HTTP receiver.
  mkdir -p "$src/third_party/unitmux"
  cp "$here"/unitmux/go.mod "$here"/unitmux/unitmux.go "$src/third_party/unitmux/"
fi

echo "== Patching"
case "$component" in
  prometheus | jaeger)
    git -C "$src" apply --whitespace=nowarn "$here/patches/$component-$version.patch"
    (
      cd "$src"
      go mod edit -require=unit.nginx.org/go@v0.0.0 -replace=unit.nginx.org/go=./third_party/unit-go
    )
    if [ "$component" = jaeger ]; then
      # The OTLP/HTTP receiver is in the OpenTelemetry collector, a dependency: a patched copy is used.
      "$here/patch-jaeger-otlp.sh" "$src"
    fi
    ;;
  victorialogs)
    "$here/patch-victorialogs.sh" "$src"
    ;;
  perses)
    "$here/patch-perses.sh" "$src"
    ;;
esac
# What we changed in the upstream files, for the license obligations (and for the reader).
git -C "$src" -c core.quotepath=off diff -- . ':!third_party' > "$work/modifications.patch"
for dependency_patch in perses-common otlpreceiver; do
  if [ -f "$src/third_party/$dependency_patch.patch" ]; then
    # The change is in a copy of a dependency (of Perses, of Jaeger).
    cat "$src/third_party/$dependency_patch.patch" >> "$work/modifications.patch"
  fi
done

if [ "$component" = prometheus ] || [ "$component" = jaeger ]; then
  # The web UI of Prometheus is built with pnpm, and the dependencies of the one of Jaeger are listed with it (not installed everywhere, and the npm package of that name is a stub).
  mkdir -p "$work/pnpm"
  case "$os-$arch" in
    linux-x86_64) pnpm_asset=pnpm-linux-x64 ;;
    linux-aarch64) pnpm_asset=pnpm-linux-arm64 ;;
    macos-x86_64) pnpm_asset=pnpm-macos-x64 ;;
    macos-aarch64) pnpm_asset=pnpm-macos-arm64 ;;
  esac
  curl -fsSL -o "$work/pnpm/pnpm" "https://github.com/pnpm/pnpm/releases/download/v$PNPM_VERSION/$pnpm_asset"
  chmod +x "$work/pnpm/pnpm"
  export PATH="$work/pnpm:$PATH"
fi

echo "== Building"
(
  cd "$src"
  export CGO_ENABLED=1
  export CGO_CFLAGS="-I$FREEUNIT_SRC/src -I$FREEUNIT_SRC/build/include"
  export CGO_LDFLAGS="-L$LIBUNIT_DIR"
  tags=""
  case "$component" in
    prometheus)
      # The web UI is embedded in the binary (builtinassets).
      make assets-compress
      tags=builtinassets
      ;;
    jaeger)
      # The web UI is embedded in the binary: download the released build of the UI version the submodule is at.
      make build-ui
      ;;
    perses)
      make build-ui generate
      ;;
  esac
  # Downloading hundreds of modules fails now and then.
  for attempt in 1 2 3; do
    go build -trimpath -tags "$tags" -ldflags="-s -w" -o "$work/$component-bin" "$package" && break
    if [ "$attempt" = 3 ]; then exit 1; fi
    echo "go build failed, trying again" >&2
    sleep 10
  done
)

echo "== Packaging"
mkdir -p "$pkg"
cp "$work/$component-bin" "$pkg/$binary"
if [ "$component" = perses ]; then
  # Plugins (data sources and panels) the UI loads, installed by `make generate`.
  cp -R "$src/plugins-archive" "$pkg/plugins-archive"
fi

# Licenses: the project's own, the ones of the Go modules in the binary, and FreeUnit's (libunit is linked in).
for f in LICENSE LICENSE.md NOTICE NOTICE.md; do
  if [ -f "$src/$f" ]; then cp "$src/$f" "$pkg/UPSTREAM-$f"; fi
done
mkdir -p "$pkg/licenses"
"$here/collect-licenses.sh" "$src" "$package" "$pkg/licenses/go-modules"
# The exact modules (and versions) in the binary.
(
  cd "$src"
  go list -deps -f '{{with .Module}}{{.Path}} {{.Version}}{{end}}' "$package" 2>/dev/null | sort -u > "$pkg/licenses/go-modules.txt"
)
# The web UI embedded in the binary is JavaScript built from npm packages: their licenses too.
case "$component" in
  prometheus)
    "$here/collect-npm-licenses.sh" pnpm "$src/web/ui" "$pkg/licenses/npm"
    "$here/collect-npm-licenses.sh" pnpm "$src/web/ui/react-app" "$pkg/licenses/npm"
    ;;
  perses)
    "$here/collect-npm-licenses.sh" npm "$src/ui" "$pkg/licenses/npm"
    ;;
  jaeger)
    # The UI is downloaded already built: install its dependencies only to read their licenses.
    export npm_config_manage_package_manager_versions=false
    (cd "$src/jaeger-ui" && retry pnpm install --frozen-lockfile --prod --ignore-scripts)
    "$here/collect-npm-licenses.sh" pnpm "$src/jaeger-ui" "$pkg/licenses/npm"
    ;;
esac
mkdir -p "$pkg/licenses/freeunit"
cp "$FREEUNIT_SRC/LICENSE" "$FREEUNIT_SRC/NOTICE" "$pkg/licenses/freeunit/"
"$here/check-licenses.sh" "$pkg"
cp "$work/modifications.patch" "$pkg/SNUNIT-MODIFICATIONS.patch"
sed -e "s|@COMPONENT@|$component|g" -e "s|@REPO@|$repo|g" -e "s|@VERSION@|$version|g" -e "s|@COMMIT@|$commit|g" \
    -e "s|@LICENSE@|$license|g" -e "s|@ROLE@|$role|g" -e "s|@TRADEMARK@|$trademark|g" -e "s|@BINARY@|$binary|g" -e "s|@FREEUNIT_REF@|$freeunit_ref|g" \
    "$here/SOURCE.md.in" > "$pkg/SNUNIT-SOURCE.md"

name="snunit-stack-$role-$os-$arch"
tar czf "$out/$name.tar.gz" -C "$work/pkg" "$role"
echo "Built $out/$name.tar.gz"
